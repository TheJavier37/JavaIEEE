package auto.learning.javier.poo.inicial.entidad;

public class Calculator {

    public int sumaSimple (int numero1, int numero2) {
        int resultado = numero1 + numero2;
        return resultado;
    }

    public int restaSimple (int numero1, int numero2) {
        int resultado = numero1 - numero2;
        return resultado;
    }

    public int multiplicacionSimple (int numero1, int numero2) {
        int resultado = numero1 * numero2;
        return resultado;
    }

    public int divisionSimple (int numero1, int numero2) {
        int resultado = numero1 / numero2;
        return resultado;
    }

}
